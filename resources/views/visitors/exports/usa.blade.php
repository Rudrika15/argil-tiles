                        if (data.success) {
                            Swal.fire({
                                title: 'Success',
                                text: 'Message sent successfully!',
                                icon: 'success'
                            });
                            form.reset();
                        } else {
                            throw new Error(data.message || 'Mail not sent');
                        }
                    })
                    .catch((error) => {
                        Swal.fire({
                            title: 'Error',
                            text: error.message || 'Something went wrong!',
                            icon: 'error'
                        });
                    })
